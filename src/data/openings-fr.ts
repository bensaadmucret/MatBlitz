/**
 * Traduit la notation PGN en notation française
 * N → C (Cavalier), B → F (Fou), R → T (Tour), Q → D (Dame), K → R (Roi)
 */
export function translatePGN(pgn: string): string {
  // Map des pièces en notation algébrique
  const pieceMap: Record<string, string> = {
    'N': 'C',  // Knight → Cavalier
    'B': 'F',  // Bishop → Fou
    'R': 'T',  // Rook → Tour
    'Q': 'D',  // Queen → Dame
    'K': 'R',  // King → Roi
  }
  
  // Remplacer chaque lettre de pièce (mais pas dans les coordonnées de cases)
  let result = pgn
    .replace(/([NBRQK])([a-h]?[1-8]?)/g, (_match, piece, square) => {
      // Ne remplacer que si c'est vraiment une pièce (suivie éventuellement d'une case)
      return pieceMap[piece] + square
    })
    .replace(/O-O-O/g, 'GrRo')  // Grand Roque
    .replace(/O-O/g, 'Ro')      // Petit Roque
    .replace(/x/g, 'x')         // Capture (déjà en commun)
    .replace(/=/g, '=')         // Promotion (déjà en commun)
    .replace(/\+/g, '+')        // Échec (déjà en commun)
    .replace(/#/g, '#')         // Mat (déjà en commun)
  
  return result
}
